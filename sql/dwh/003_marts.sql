-- Витрины: звёздная схема для продаж и остатков.
--
-- Измерение товара нормализовано в «снежинку» (товар -> подкатегория ->
-- категория -> группа): иерархию правят категорийные менеджеры, и держать её
-- в одном месте дешевле, чем обновлять тысячи строк товаров. Для BI поверх
-- снежинки есть плоское представление v_product.
--
-- Суррогатные ключи -1 и -2 зарезервированы:
--   -1  неизвестно / не применимо (анонимная покупка, товара нет в каталоге)
--   -2  ссылка есть, но в источнике записи нет (клиент из заказа не найден в CRM)

CREATE SCHEMA IF NOT EXISTS marts;

-- ------------------------------------------------------------------ даты
CREATE TABLE marts.dim_date (
    date_key      integer PRIMARY KEY,  -- 20260930
    date          date    NOT NULL UNIQUE,
    year          smallint NOT NULL,
    quarter       smallint NOT NULL,
    month         smallint NOT NULL,
    month_name    text    NOT NULL,
    iso_week      smallint NOT NULL,
    day_of_week   smallint NOT NULL,  -- 1 = понедельник
    day_name      text    NOT NULL,
    is_weekend    boolean NOT NULL,
    is_holiday    boolean NOT NULL
);

INSERT INTO marts.dim_date
SELECT to_char(d, 'YYYYMMDD')::int,
       d,
       extract(year FROM d),
       extract(quarter FROM d),
       extract(month FROM d),
       (ARRAY['январь','февраль','март','апрель','май','июнь','июль','август',
              'сентябрь','октябрь','ноябрь','декабрь'])[extract(month FROM d)],
       extract(week FROM d),
       extract(isodow FROM d),
       (ARRAY['пн','вт','ср','чт','пт','сб','вс'])[extract(isodow FROM d)],
       extract(isodow FROM d) IN (6, 7),
       -- государственные праздники РК с фиксированной датой
       to_char(d, 'MM-DD') IN ('01-01', '01-02', '03-08', '03-21', '03-22', '03-23', '05-01',
                               '05-07', '05-09', '07-06', '08-30', '10-25', '12-16')
FROM generate_series(date '2020-01-01', date '2030-12-31', interval '1 day') AS g(d);

