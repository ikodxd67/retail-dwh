-- ---------------------------------------------------- товары (снежинка)
CREATE TABLE marts.dim_product_group (
    group_sk    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_name  text NOT NULL UNIQUE
);

CREATE TABLE marts.dim_product_category (
    category_sk    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_sk       integer NOT NULL REFERENCES marts.dim_product_group,
    category_name  text    NOT NULL,
    UNIQUE (group_sk, category_name)
);

CREATE TABLE marts.dim_product_subcategory (
    subcategory_sk    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_sk       integer NOT NULL REFERENCES marts.dim_product_category,
    subcategory_name  text    NOT NULL,
    UNIQUE (category_sk, subcategory_name)
);

INSERT INTO marts.dim_product_group (group_sk, group_name) VALUES (-1, 'Без категории');
INSERT INTO marts.dim_product_category (category_sk, group_sk, category_name)
VALUES (-1, -1, 'Без категории');
INSERT INTO marts.dim_product_subcategory (subcategory_sk, category_sk, subcategory_name)
VALUES (-1, -1, 'Без категории');

CREATE TABLE marts.dim_product (
    product_sk         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hk_product         uuid    UNIQUE,
    sku                text    NOT NULL,
    name               text,
    brand              text,
    unit               text,
    status             text,
    subcategory_sk     integer NOT NULL DEFAULT -1 REFERENCES marts.dim_product_subcategory,
    supplier_code      text,
    purchase_currency  text,
    retail_price       numeric(12,2),
    in_catalog         boolean NOT NULL DEFAULT true,
    updated_at         timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX dim_product_subcategory_ix ON marts.dim_product (subcategory_sk);
INSERT INTO marts.dim_product (product_sk, sku, name, in_catalog)
VALUES (-1, '?', 'Неизвестный товар', false);

CREATE VIEW marts.v_product AS
SELECT p.product_sk, p.sku, p.name, p.brand, p.unit, p.status, p.retail_price,
       p.purchase_currency, p.in_catalog,
       s.subcategory_name, c.category_name, g.group_name
FROM marts.dim_product p
JOIN marts.dim_product_subcategory s USING (subcategory_sk)
JOIN marts.dim_product_category c USING (category_sk)
JOIN marts.dim_product_group g USING (group_sk);

