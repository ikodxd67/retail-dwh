-- -------------------------------------------------------- факт продаж
-- Зерно: строка заказа. Номер заказа и строки — вырожденное измерение.
-- Секционирование по месяцам: отчёты почти всегда режут по периоду, а
-- пересборка месяца сводится к работе с одной секцией.
CREATE TABLE marts.fact_sales (
    date_key           integer NOT NULL REFERENCES marts.dim_date,
    order_no           text    NOT NULL,
    line_no            integer NOT NULL,
    order_ts           timestamptz NOT NULL,
    store_sk           integer NOT NULL,
    product_sk         integer NOT NULL,
    customer_sk        bigint  NOT NULL,
    hk_customer        uuid,
    channel            text    NOT NULL,
    payment_type       text,
    order_status       text    NOT NULL,
    promo_campaign_id  text,
    qty                numeric(10,3) NOT NULL,
    unit_price         numeric(12,2) NOT NULL,
    gross_amount       numeric(14,2) NOT NULL,
    discount_amount    numeric(14,2) NOT NULL,
    net_amount         numeric(14,2) NOT NULL,  -- 0 для отменённых и возвращённых
    unit_cost_kzt      numeric(14,2),
    cost_amount        numeric(14,2),
    margin_amount      numeric(14,2),
    fx_rate_date       date,
    row_hash           uuid    NOT NULL,
    updated_at         timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (date_key, order_no, line_no)
) PARTITION BY RANGE (date_key);

DO $$
DECLARE m date;
BEGIN
    FOR m IN SELECT generate_series(date '2024-12-01', date '2027-12-01', interval '1 month') LOOP
        EXECUTE format(
            'CREATE TABLE marts.fact_sales_%s PARTITION OF marts.fact_sales FOR VALUES FROM (%s) TO (%s)',
            to_char(m, 'YYYYMM'), to_char(m, 'YYYYMMDD'),
            to_char(m + interval '1 month', 'YYYYMMDD'));
    END LOOP;
END $$;
CREATE TABLE marts.fact_sales_default PARTITION OF marts.fact_sales DEFAULT;

CREATE INDEX fact_sales_store_ix ON marts.fact_sales (store_sk, date_key);
CREATE INDEX fact_sales_product_ix ON marts.fact_sales (product_sk);
CREATE INDEX fact_sales_customer_ix ON marts.fact_sales (hk_customer, order_ts);

